/**
 * Frontend security: role/permission route guards, a hardened auth store
 * (the access token is memory-only — never persisted to localStorage, so
 * an XSS payload reading storage cannot steal it), and an Axios client that
 * transparently refreshes via the httpOnly refresh-token cookie the
 * Authentication module now issues. Extends Phase 6's output in place —
 * `api-client.ts` and `auth.store.ts` are replaced at the same paths;
 * everything else here is new.
 */
