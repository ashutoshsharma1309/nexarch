/* ── src/shared/security/cookies.ts ──────────────────────────────────────── */

const cookiesUtil = `import type { Request, Response } from 'express';

import { config } from '../config/index.js';

const REFRESH_COOKIE = 'refreshToken';
const REFRESH_MAX_AGE_MS = 7 * 24 * 60 * 60 * 1000;

/** Refresh tokens live in an httpOnly cookie — never reachable from JS, so an XSS payload cannot exfiltrate it. */
export function setRefreshTokenCookie(res: Response, token: string): void {
  res.cookie(REFRESH_COOKIE, token, {
    httpOnly: true,
    secure: config.cookies.secure,
    sameSite: config.cookies.sameSite,
    path: config.server.apiPrefix + '/auth',
    maxAge: REFRESH_MAX_AGE_MS,
  });
}

export function clearRefreshTokenCookie(res: Response): void {
  res.clearCookie(REFRESH_COOKIE, { path: config.server.apiPrefix + '/auth' });
}

export function readRefreshTokenCookie(req: Request): string | undefined {
  const cookies = req.cookies as Record<string, string> | undefined;
  return cookies?.[REFRESH_COOKIE];
}
`;

/* ── src/shared/security/csrf.ts ─────────────────────────────────────────── */

const csrfUtil = `import { randomBytes } from 'node:crypto';

import type { RequestHandler, Response } from 'express';

import { config } from '../config/index.js';
import { ForbiddenError } from '../errors/app-error.js';

const CSRF_COOKIE = 'csrfToken';
const CSRF_HEADER = 'x-csrf-token';

/**
 * Double-submit-cookie CSRF protection for the two cookie-authenticated
 * routes (refresh, logout) — every other route authenticates with a bearer
 * token, which a cross-site request cannot forge, so it doesn't need this.
 */
export const csrfProtection: RequestHandler = (req, _res, next) => {
  const cookies = req.cookies as Record<string, string> | undefined;
  const cookieToken = cookies?.[CSRF_COOKIE];
  const headerToken = req.get(CSRF_HEADER);
  if (!cookieToken || !headerToken || cookieToken !== headerToken) {
    next(new ForbiddenError('CSRF token missing or invalid'));
    return;
  }
  next();
};

/** Issues a fresh CSRF token cookie (readable by the frontend so it can echo it back as a header). */
export function issueCsrfCookie(res: Response): string {
  const token = randomBytes(24).toString('hex');
  res.cookie(CSRF_COOKIE, token, {
    httpOnly: false,
    secure: config.cookies.secure,
    sameSite: config.cookies.sameSite,
    path: '/',
  });
  return token;
}
`;

