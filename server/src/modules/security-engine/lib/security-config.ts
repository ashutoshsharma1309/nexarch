/* ── src/app.ts (replaces Phase 5's) ─────────────────────────────────────── */

function appTs(projectName: string): string {
  return `import compression from 'compression';
import cookieParser from 'cookie-parser';
import cors from 'cors';
import express from 'express';
import type { Express } from 'express';
import helmet from 'helmet';
import swaggerUi from 'swagger-ui-express';

import { config } from './shared/config/index.js';
import { errorHandler, notFoundHandler } from './shared/middleware/error-handler.js';
import { requestContext } from './shared/middleware/request-context.js';
import { requestLogger } from './shared/middleware/request-logger.js';
import { sanitizeInput } from './shared/middleware/sanitize.js';
import { apiLimiter } from './shared/security/rate-limiters.js';
import { buildApiRouter } from './routes.js';
import { openApiDocument } from './docs/openapi.js';

/**
 * ${projectName} API — assembled here, listened on in index.ts.
 * Pipeline order: context → security headers → CORS → cookies → parsing →
 * sanitization → logging → rate limit → docs → modules → 404 → errors.
 *
 * Content-Security-Policy is intentionally left off the global helmet
 * config: this process only ever serves JSON plus the Swagger UI docs page
 * (which needs inline styles/scripts CSP would block) — CSP belongs on the
 * surface that actually renders untrusted HTML, i.e. the generated
 * frontend's hosting layer, not a JSON API.
 */
export function createApp(): Express {
  const app = express();
  app.disable('x-powered-by');
  app.set('trust proxy', 1);

  app.use(requestContext);
  app.use(
    helmet({
      contentSecurityPolicy: false,
      hsts: { maxAge: 15_552_000, includeSubDomains: true, preload: true },
      referrerPolicy: { policy: 'no-referrer' },
      crossOriginResourcePolicy: { policy: 'same-site' },
    }),
  );
  app.use(
    cors({
      origin: config.cors.origins.includes('*') ? true : config.cors.origins,
      credentials: true,
    }),
  );
  app.use(compression());
  app.use(cookieParser(config.cookies.secret));
  app.use(express.json({ limit: config.server.bodyLimit }));
  app.use(express.urlencoded({ extended: false, limit: config.server.bodyLimit }));
  app.use(sanitizeInput);
  app.use(requestLogger);
  app.use(apiLimiter);

  app.get(config.server.apiPrefix + '/health', (_req, res) => {
    res.json({ success: true, message: 'OK', data: { status: 'ok' }, meta: {} });
  });

  app.use('/docs', swaggerUi.serve, swaggerUi.setup(openApiDocument));
  app.use(config.server.apiPrefix, buildApiRouter());

  app.use(notFoundHandler);
  app.use(errorHandler);

  return app;
}
`;
}

