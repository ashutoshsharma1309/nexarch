/**
 * What else does this touch?
 *
 * Pure graph traversal — no model call. If the Payment service changes,
 * the things at risk are the things that reach it: the Order service that
 * uses it, the endpoints that expose those, the pages that call them. The
 * graph already records every one of those relationships, so the answer is
 * a walk, not a judgement.
 *
 * Direction is `incoming`, which is the part worth getting right. A
 * node's *dependencies* are what it needs; its *dependents* are what
 * breaks when it changes. Impact analysis wants the second, so it walks
 * edges backwards — from a node to whatever points at it.
 *
 * One exception: `CONTAINS` is followed downward as well. Changing an
 * entity affects its fields even though the fields point at nothing.
 */
import type {
  GraphNode,
  GraphNodeType,
  GraphRelationship,
  HopDirection,
  ImpactAnalysis,
  ImpactedNode,
  TraversalResult,
} from '../../../shared/contracts/engineering-graph.js';
import { indexGraph, traverseBounded } from './graph-queries.js';
import type { GraphIndex } from './graph-queries.js';

/**
 * How many impacted nodes one answer may carry. Reached rather than
 * exceeded: the cap being hit is reported on the analysis, because an
 * impact answer that quietly stops at 400 is how a change ships believing
 * it broke nothing.
 */
const IMPACT_LIMIT = 400;

/**
 * What a neighbour that points *at* the changed node does to it.
 *
 * These are phrased from the neighbour's side on purpose. The walk follows
 * incoming edges, so the neighbour is the edge's *source* and the changed
 * node its target — and the table used to be phrased the other way round,
 * which inverted every row it produced. An incoming `CONTAINS` means the
 * neighbour is the changed node's parent, and the line read "<parent> is
 * contained by the changed node": not a clumsy phrasing but the opposite of
 * the real dependency direction, on the one screen a reader consults to
 * decide what a change is safe to touch.
 */
const INBOUND_VERBS: Record<GraphRelationship, string> = {
  CONTAINS: 'contains',
  IMPLEMENTS: 'implements',
  DEPENDS_ON: 'depends on',
  USES: 'uses',
  CALLS: 'calls',
  EXPOSES: 'exposes',
  PERSISTS: 'persists',
  BELONGS_TO: 'holds a reference to',
  GENERATES: 'generates',
  VALIDATES: 'validates',
  TESTS: 'tests',
  SECURED_BY: 'is secured by',
  TARGETS: 'reports a finding against',
};

/** The mirror, for the downward walk: the changed node is the edge's source. */
const OUTBOUND_VERBS: Record<GraphRelationship, string> = {
  CONTAINS: 'is contained by',
  IMPLEMENTS: 'is implemented by',
  DEPENDS_ON: 'is depended on by',
  USES: 'is used by',
  CALLS: 'is called by',
  EXPOSES: 'is exposed by',
  PERSISTS: 'is persisted by',
  BELONGS_TO: 'is referenced by',
  GENERATES: 'is generated by',
  VALIDATES: 'is validated by',
  TESTS: 'is tested by',
  SECURED_BY: 'secures',
  TARGETS: 'is the subject of a finding from',
};

/**
 * Why this node is in the answer, in one line.
 *
 * Only a depth-1 hit touches the changed node itself. Deeper hits arrived
 * through a chain, and the edge that reached them joins them to their
 * predecessor rather than to the origin — so the line says so and gives the
 * distance, instead of asserting a direct relationship the graph does not
 * hold.
 */
function reasonFor(
  name: string,
  via: GraphRelationship,
  direction: HopDirection,
  depth: number,
): string {
  const verb = direction === 'backward' ? INBOUND_VERBS[via] : OUTBOUND_VERBS[via];
  if (depth === 1) return `${name} ${verb} the changed node`;
  return `${name} ${verb} a node the change affects (${String(depth)} hops away)`;
}

export function analyzeImpact(index: GraphIndex, origin: GraphNode, maxDepth = 3): ImpactAnalysis {
  // Dependents: everything that points at this node, transitively. Each hit
  // was reached by walking an edge backwards, from target to source.
  const upstream = traverseBounded(index, origin.id, 'incoming', {
    maxDepth,
    limit: IMPACT_LIMIT,
  });

  // Contained children: changing a table changes its columns, and those
  // are reached by following CONTAINS forwards rather than backwards.
  const contained = traverseBounded(index, origin.id, 'outgoing', {
    maxDepth,
    relationships: ['CONTAINS', 'GENERATES'],
    limit: IMPACT_LIMIT,
  });

  const seen = new Set<string>([origin.id]);
  const impacted: ImpactedNode[] = [];

  const walks: { direction: HopDirection; result: TraversalResult }[] = [
    { direction: 'backward', result: upstream },
    { direction: 'forward', result: contained },
  ];

  for (const { direction, result } of walks) {
    for (const related of result.related) {
      if (seen.has(related.node.id)) continue;
      seen.add(related.node.id);
      impacted.push({
        node: related.node,
        depth: related.depth,
        via: related.via,
        direction,
        direct: related.depth === 1,
        reason: reasonFor(related.node.name, related.via, direction, related.depth),
      });
    }
  }

  impacted.sort((a, b) => a.depth - b.depth || a.node.type.localeCompare(b.node.type));

  const summary: Partial<Record<GraphNodeType, number>> = {};
  for (const entry of impacted) {
    summary[entry.node.type] = (summary[entry.node.type] ?? 0) + 1;
  }

  const directCount = impacted.filter((entry) => entry.direct).length;

  return {
    origin,
    impacted,
    summary,
    directCount,
    indirectCount: impacted.length - directCount,
    maxDepth,
    truncated: upstream.truncated || contained.truncated,
  };
}

/** Convenience for callers holding raw nodes/edges rather than an index. */
export function analyzeImpactFor(
  nodes: GraphNode[],
  edges: Parameters<typeof indexGraph>[1],
  origin: GraphNode,
  maxDepth = 3,
): ImpactAnalysis {
  return analyzeImpact(indexGraph(nodes, edges), origin, maxDepth);
}
