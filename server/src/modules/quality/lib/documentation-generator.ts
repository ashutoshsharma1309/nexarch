function developerGuide(artifacts: QualityArtifacts): string {
  return `# Developer Guide — ${artifacts.projectName}

## Conventions

- Strict TypeScript, no implicit \`any\`.
- Feature-first folders; modules never import each other's internals.
- One success response envelope, one error envelope, applied everywhere.
- Tests live under \`test/\` (backend) and \`test/\` (frontend), generated by
  the Quality Engine — see \`testing-report.json\` for what's already
  scaffolded.

## Adding a feature

1. Plan the change with the Dependency Graph's impact simulation before
   touching code — it tells you exactly which files a change affects.
2. Extend the schema (Prisma) if needed, then the module's
   validator → service → controller → router chain.
3. Add the corresponding frontend feature folder and wire its route.
4. Regenerate tests and documentation from the Quality Engine.

## Modules

${artifacts.backend?.modules.length ? artifacts.backend.modules.map((m) => `- ${m}`).join('\n') : '_No backend modules generated yet._'}
`;
}

function contributing(): string {
  return `# Contributing

## Workflow

1. Fork and branch from \`main\`.
2. Keep commits scoped — one logical change per commit.
3. Run \`npm run lint\` and \`npm test\` before opening a PR.
4. Describe *why* the change is needed, not just what it does.

## Code style

Enforced by ESLint + Prettier — run \`npm run lint:fix\` to auto-fix most
issues before committing.

## Commit messages

Present tense, imperative mood: "add X", "fix Y", not "added X" or
"fixes Y".
`;
}

