function systemArchitecture(artifacts: QualityArtifacts): string {
  const choice = artifacts.architecture?.decisions?.architecture?.choice;
  const backendModuleCount = artifacts.backend?.modules.length ?? 0;
  const frontendPageCount = artifacts.frontend?.pages.length ?? 0;
  const graph = artifacts.dependencyGraph?.stats;

  return `# System Architecture — ${artifacts.projectName}

## Pattern

${choice ?? 'Not yet planned — run the Architecture Planner.'}

## Scale

- ${backendModuleCount} backend module(s)
- ${frontendPageCount} frontend page(s)
${graph ? `- ${graph.totalNodes} dependency graph nodes, ${graph.totalEdges} edges, average depth ${graph.averageDependencyDepth}` : ''}

## Layering

Each backend module owns its own controller → service → repository chain
and never imports another module's internals — cross-module data only
flows through shared types. The frontend mirrors this with a feature-first
folder per page/domain, sharing only UI primitives and the API client
layer.

## Data flow

1. Client calls a versioned REST endpoint (\`/api/v1/...\`).
2. The router validates the request shape, the controller narrows it,
   the service executes business logic, the repository (Prisma) persists it.
3. Responses follow one success envelope and one error envelope across
   every endpoint.

## Where to look

| Concern | Location |
| --- | --- |
| Routes | \`backend/src/modules/*/*.router.ts\` |
| Business logic | \`backend/src/modules/*/*.service.ts\` |
| Validation | \`backend/src/modules/*/*.validator.ts\` |
| Shared types | \`backend/src/shared/types/\` |
| Pages | \`frontend/src/features/*/\` |
| API client | \`frontend/src/shared/services/\` |
`;
}

function apiDocumentation(artifacts: QualityArtifacts): string {
  const routes = artifacts.backend?.routes ?? [];
  const grouped = new Map<string, { method: string; path: string }[]>();
  for (const route of routes) {
    const group = route.path.split('/').find(Boolean) ?? 'root';
    const list = grouped.get(group) ?? [];
    list.push(route);
    grouped.set(group, list);
  }

  const lines = [
    `# API Documentation — ${artifacts.projectName}`,
    '',
    `${routes.length} endpoint(s).`,
    '',
  ];
  for (const [group, groupRoutes] of grouped) {
    lines.push(`## ${group}`, '');
    for (const route of groupRoutes)
      lines.push(`- \`${route.method} /${group === 'root' ? '' : group}...\``);
    lines.push('');
  }
  if (routes.length === 0) lines.push('_No routes available — generate the backend first._');
  return lines.join('\n');
}

function databaseDocumentation(artifacts: QualityArtifacts): string {
  const tables = artifacts.databaseDesign?.tables ?? [];
  const lines = [
    `# Database Documentation — ${artifacts.projectName}`,
    '',
    `Engine: ${artifacts.architecture?.database?.engine ?? 'not yet designed'}`,
    '',
    `${tables.length} table(s): ${tables.map((t) => t.entity).join(', ') || 'none yet'}`,
    '',
    'See `schema.prisma` and `schema.sql` (Database Designer exports) for the full column-level definition.',
  ];
  return lines.join('\n');
}

function securityGuide(artifacts: QualityArtifacts): string {
  const security = artifacts.security;
  const lines = [`# Security Guide — ${artifacts.projectName}`, ''];
  if (security) {
    lines.push(
      `**Score:** ${security.report.overallScore}/100 (${security.report.grade})`,
      '',
      `OWASP Top 10 (2021): ${security.owasp.passed} passed, ${security.owasp.warned} warned, ${security.owasp.failed} failed.`,
      '',
      '## Recommendations',
      '',
      ...security.report.recommendations.map((r) => `- ${r}`),
    );
  } else {
    lines.push('_Run the Security Engine to populate this guide._');
  }
  return lines.join('\n');
}

