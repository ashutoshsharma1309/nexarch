export function generateDocumentationBundle(artifacts: QualityArtifacts): DocumentationBundle {
  const files: DocumentationFile[] = [
    { kind: 'readme', filename: 'README.md', content: readme(artifacts) },
    {
      kind: 'system-architecture',
      filename: 'SYSTEM_ARCHITECTURE.md',
      content: systemArchitecture(artifacts),
    },
    {
      kind: 'api-documentation',
      filename: 'API_DOCUMENTATION.md',
      content: apiDocumentation(artifacts),
    },
    {
      kind: 'database-documentation',
      filename: 'DATABASE_DOCUMENTATION.md',
      content: databaseDocumentation(artifacts),
    },
    { kind: 'security-guide', filename: 'SECURITY_GUIDE.md', content: securityGuide(artifacts) },
    { kind: 'deployment-guide', filename: 'DEPLOYMENT_GUIDE.md', content: deploymentGuide() },
    { kind: 'developer-guide', filename: 'DEVELOPER_GUIDE.md', content: developerGuide(artifacts) },
    { kind: 'contributing', filename: 'CONTRIBUTING.md', content: contributing() },
    { kind: 'changelog', filename: 'CHANGELOG.md', content: changelog(artifacts) },
    { kind: 'license', filename: 'LICENSE', content: license() },
  ];

  return { files };
}
